"""Generate the Kapar voiceover (AI placeholder) one line per scene.

Usage: HF_HUB_DISABLE_XET=1 python3 -I scripts/gen-vo.py
Writes public/kapar/vo/<scene>.wav and src/kapar/vo.ts (durations + word timings
for karaoke captions). Model: facebook/mms-tts-zlm (Meta MMS, Malay), CC-BY-NC 4.0 —
a PREVIEW voice; replace with the agent's own recording for the final post.

`say` is a phonetic spelling for the TTS (English loan words written as they are
pronounced in Malay); `text` is what the captions show.
"""
import json
import os

import numpy as np
import scipy.io.wavfile as wavfile
import torch
from transformers import AutoTokenizer, VitsModel

LINES = [
    ('hook', 'Okey, kalau korang tengah cari rumah area Kapar, boleh tengok yang ni.',
     'Okey, kalau korang tengah cari rumah eria Kapar, boleh tengok yang ni.'),
    ('reveal', 'Projek baru dekat Tok Muda, Kapar.', 'Projek baru dekat Tok Muda, Kapar.'),
    ('orbit', 'Lebih kurang 5km dari Pekan Kapar.', 'Lebih kurang lima kilometer dari Pekan Kapar.'),
    ('package', 'Booking bermula RM500, dan ada pakej rebate serta beberapa legal fees yang ditanggung oleh pemaju, tertakluk pada terma semasa.',
     'Buking bermula lima ratus ringgit, dan ada pakej ribet, serta beberapa ligel fis yang ditanggung oleh pemaju, tertakluk pada terma semasa.'),
    ('specs', 'Rumah ni hak milik kekal, Rizab Melayu, saiz tanah 20 x 64, ada 4 bilik tidur dan 2 bilik air.',
     'Rumah ni hak milik kekal, Rizab Melayu, saiz tanah dua puluh kali enam puluh empat, ada empat bilik tidur, dan dua bilik air.'),
    ('cta', 'Kalau nak tengok full details, kelayakan dan kira anggaran, boleh DM atau komen "nak".',
     'Kalau nak tengok ful ditels, kelayakan, dan kira anggaran, boleh di em, atau komen, nak.'),
]
RATE = 1.12  # a touch faster than default for TikTok pacing

out_dir = 'public/kapar/vo'
os.makedirs(out_dir, exist_ok=True)
model = VitsModel.from_pretrained('facebook/mms-tts-zlm')
tok = AutoTokenizer.from_pretrained('facebook/mms-tts-zlm')
model.config.speaking_rate = RATE
sr = model.config.sampling_rate

meta = {}
for sid, text, say in LINES:
    torch.manual_seed(7)
    with torch.no_grad():
        y = model(**tok(say, return_tensors='pt')).waveform[0].numpy()
    # trim leading/trailing near-silence
    idx = np.where(np.abs(y) > 0.02)[0]
    y = y[max(0, idx[0] - int(0.03 * sr)): idx[-1] + int(0.08 * sr)]
    y = (y / max(1e-6, np.abs(y).max()) * 0.89).astype(np.float32)
    wavfile.write(f'{out_dir}/{sid}.wav', sr, y)
    dur = len(y) / sr
    # word timings: proportional to characters (+ small weight per pause mark)
    words = text.split(' ')
    spoken = {'5km': 'lima kilometer', 'RM500,': 'lima ratus ringgit,', '20': 'dua puluh', 'x': 'kali', '64,': 'enam puluh empat,',
              '4': 'empat', '2': 'dua', 'DM': 'di em', '"nak".': 'nak.'}
    weights = [len(spoken.get(w, w).strip(',."')) + (4 if w.endswith((',', '.')) else 0) + 1 for w in words]
    tot = sum(weights)
    t = 0.0
    wt = []
    for w, k in zip(words, weights):
        d = dur * k / tot
        wt.append({'text': w, 'start': round(t, 3), 'end': round(t + d, 3)})
        t += d
    meta[sid] = {'dur': round(dur, 3), 'words': wt}
    print(sid, round(dur, 2), 's')

with open('src/kapar/vo.ts', 'w') as f:
    f.write('// GENERATED by scripts/gen-vo.py — AI placeholder voice (facebook/mms-tts-zlm).\n')
    f.write('export type VoWord = {text: string; start: number; end: number};\n')
    f.write('export const vo: Record<string, {dur: number; words: VoWord[]}> = ' + json.dumps(meta, ensure_ascii=False) + ';\n')
